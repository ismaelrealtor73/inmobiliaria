function slugify(text) {
  return String(text || '')
    .toLowerCase()
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function getPropertyUrl(p) {
  return BASE + '/propiedad/' + slugify(p.title_es || p.title_en) + '-' + p.id;
}

