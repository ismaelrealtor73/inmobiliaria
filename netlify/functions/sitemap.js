function staticBlock(p) {
  return [
    '    <loc>' + p.loc + '</loc>',
    '    <xhtml:link rel="alternate" hreflang="es" href="' + p.es + '"/>',
    '    <xhtml:link rel="alternate" hreflang="en" href="' + p.en + '"/>',
    '    <lastmod>' + p.last + '</lastmod>',
    '    <changefreq>' + p.freq + '</changefreq>',
    '    <priority>' + p.prio + '</priority>'
  ].join('\n');
}

function propBlock(p) {
  const last = String(p.updatedAt || p.createdAt || new Date().toISOString().slice(0, 10)).slice(0, 10);
  return [
    '    <loc>' + getPropertyUrl(p) + '</loc>',
    '    <lastmod>' + last + '</lastmod>',
    '    <changefreq>weekly</changefreq>',
    '    <priority>0.6</priority>'
  ].join('\n');
}

export async function handler() {
  let props = [];
  let dbg = '';
  try {
    const store = getStore('crm');
    const raw = await store.get('data', { type: 'text' });
    dbg = 'raw=' + (raw == null ? 'null' : 'len' + raw.length) + ' head=' + (raw != null ? raw.slice(0, 80) : '');
    const data = raw ? JSON.parse(raw) : {};
    props = (data.properties || []).filter(p => p.status === 'published').sort((a, b) => (a.id || 0) - (b.id || 0));
    dbg += ' | props=' + props.length;
  } catch (e) {
    dbg = 'EXC ' + (e && e.message ? e.message : e);
    console.error('sitemap: no se pudo leer el store', e);
  }
  const xml = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- ' + dbg + ' -->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"',
    '        xmlns:xhtml="http://www.w3.org/1999/xhtml">',
    ...STATIC_PAGES.map(p => '  <url>\n' + staticBlock(p) + '\n  </url>'),
    ...props.map(p => '  <url>\n' + propBlock(p) + '\n  </url>'),
    '</urlset>'
  ].join('\n');
  return {
    statusCode: 200,
    headers: { 'Content-Type': 'application/xml; charset=utf-8' },
    body: xml
  };
}
